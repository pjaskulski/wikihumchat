const storageKey = "wikihum-chat-language";

export function language(document) {
  return document.documentElement.lang === "en" ? "en" : "pl";
}

export function translate(document, source) {
  if (language(document) !== "en") return source;
  if (Object.hasOwn(english, source)) return english[source];
  if (source.endsWith(" (nowa karta)")) return source.slice(0, -" (nowa karta)".length) + " (new tab)";
  if (source.startsWith("Wykorzystanie wcześniejszych wyników: ")) {
    return "Reusing earlier results: " + translate(document, source.slice("Wykorzystanie wcześniejszych wyników: ".length));
  }
  const diagnostic = source.indexOf(" Identyfikator diagnostyczny: ");
  if (diagnostic !== -1) {
    return translate(document, source.slice(0, diagnostic))
      + " Diagnostic ID: " + source.slice(diagnostic + " Identyfikator diagnostyczny: ".length);
  }
  // Zmienne fragmenty pochodzą z postępu, czasu lub komunikatów błędów.
  // Tłumaczymy wyłącznie znany prefiks; nazwy rekordów i hasła pozostają danymi.
  for (const prefix of ["Analizowanie wyników wyszukiwania", "Wyszukiwanie",
    "Ustalanie sposobu zapisu informacji", "Analizowanie danych", "Sprawdzanie danych",
    "Poprawianie wywołania narzędzia", "Czas odpowiedzi"]) {
    if (source.startsWith(prefix + ": ")) return english[prefix] + (prefix === "Czas odpowiedzi" ? source.slice(prefix.length).replace(",", ".") : source.slice(prefix.length));
  }
  const count = /^Pokaż cały przebieg \((\d+)\)$/.exec(source);
  if (count) return `Show all steps (${count[1]})`;
  const state = /^(W toku…|Zakończono|Błąd|Wymaga weryfikacji) · (.+)$/.exec(source);
  if (state) return `${english[state[1]]} · ${state[2].replace(",", ".")}`;
  const http = /^(Błąd konfiguracji dostępu do modelu|Serwer modelu odrzucił żądanie|Serwer modelu zwrócił błąd)( \(HTTP \d+\)\.)(.*)$/.exec(source);
  if (http) return english[http[1]] + http[2] + translate(document, http[3]);
  const rate = /^Przekroczono limit zapytań\. Spróbuj ponownie za (\d+) s\.$/.exec(source);
  if (rate) return `The request limit has been exceeded. Please try again in ${rate[1]} s.`;
  return source;
}

export function setText(node, source) {
  node.dataset.i18n = source;
  node.textContent = translate(node.ownerDocument, source);
}

export function setTranslatedAttribute(node, attribute, source) {
  node.setAttribute(`data-i18n-${attribute}`, source);
  node.setAttribute(attribute, translate(node.ownerDocument, source));
}

export function mountLanguage(document) {
  const window = document.defaultView;
  const switcher = document.getElementById("language-switch");
  const buttons = [...document.querySelectorAll("[data-language]")];
  function apply(value) {
    document.documentElement.lang = value === "en" ? "en" : "pl";
    for (const node of document.querySelectorAll("[data-i18n]")) {
      node.textContent = translate(document, node.dataset.i18n);
    }
    for (const attribute of ["aria-label", "placeholder", "alt", "title", "content"]) {
      for (const node of document.querySelectorAll(`[data-i18n-${attribute}]`)) {
        node.setAttribute(attribute, translate(document, node.getAttribute(`data-i18n-${attribute}`)));
      }
    }
    for (const example of document.querySelectorAll("[data-question-pl]")) {
      const question = language(document) === "en"
        ? example.dataset.questionEn || example.dataset.questionPl : example.dataset.questionPl;
      example.dataset.question = question;
      example.querySelector("[data-example-text]").textContent = question;
    }
    for (const button of buttons) {
      button.setAttribute("aria-pressed", String(button.dataset.language === language(document)));
    }
    window.dispatchEvent(new window.Event("languagechange"));
  }
  function readPreference() {
    try { return window.localStorage.getItem(storageKey); } catch { return "pl"; }
  }
  function choose(event) {
    const value = event.currentTarget.dataset.language;
    try { window.localStorage.setItem(storageKey, value); } catch { /* Działa także bez pamięci. */ }
    apply(value);
  }
  function stored(event) {
    if (event.key === storageKey || event.key === null) apply(readPreference());
  }
  for (const button of buttons) button.addEventListener("click", choose);
  window.addEventListener("storage", stored);
  apply(readPreference());
  if (switcher) switcher.hidden = false;
  return {
    destroy() {
      for (const button of buttons) button.removeEventListener("click", choose);
      window.removeEventListener("storage", stored);
    },
  };
}
